export function languageSwitcher(current) {
  const live = liveLocales();
  if (!live.length) return "";
  const cur = current ? resolve(current).code : "pt";
  const item = l => {
    const label = `${l.flag}&nbsp;${l.name}`;
    return l.code === cur
      ? `<span aria-current="page" style="color:#16181D;">${label}</span>`
      : `<a href="${l.prefix || "/"}" hreflang="${l.lang}" style="color:#5B606B;">${label}</a>`;
  };
  return `<span class="mono" lang="${escapeAttr(LOCALES[cur].lang)}">${[LOCALES.pt, ...live].map(item).join("&nbsp;· ")}</span>`;
}

function escapeAttr(s) {
  return String(s).replace(/"/g, "&quot;");
}

export function parseAs24Id(q) {
  const s = String(q || "").trim();
  if (!s) return null;
  const uuid = /([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})\s*$/i.exec(s.replace(/[?#].*$/, "").replace(/\/+$/, ""));
  if (uuid) return uuid[1].toLowerCase();
  if (/^https?:\/\//i.test(s)) return null;
  return /^[a-z0-9][a-z0-9-]{3,60}$/i.test(s) ? s.toLowerCase() : null;
}

