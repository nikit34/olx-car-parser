export const INTL_CODES = Object.keys(LOCALES).filter(c => c !== "pt");

export const KEYS = Object.keys(STRINGS_DE);

export function missingKeys() {
  const out = {};
  for (const [code, l] of Object.entries(LOCALES)) {
    const have = new Set(Object.keys(l.strings));
    const missing = KEYS.filter(k => !have.has(k));
    const extra = [...have].filter(k => !KEYS.includes(k));
    if (missing.length || extra.length) out[code] = { missing, extra };
  }
  return out;
}

function resolve(loc) {
  const l = typeof loc === "string" ? LOCALES[loc] : loc;
  if (!l || !l.code) throw new Error(`unknown locale: ${String(loc)}`);
  return l;
}

export function t(loc, key, vars = null) {
  const l = resolve(loc);
  const s = l.strings[key];
  if (typeof s !== "string") throw new Error(`i18n: missing key "${key}" for locale ${l.code}`);
  if (!vars) return s;
  return s.replace(/\{([a-z_]+)\}/g, (m, k) => {
    if (!Object.prototype.hasOwnProperty.call(vars, k)) return m;
    const v = vars[k];
    return v == null ? "" : String(v);
  });
}

export function href(loc, route, ...segments) {
  const l = resolve(loc);
  if (route === "landing") return l.prefix || "/";
  const seg = l.routes[route];
  if (!seg) throw new Error(`i18n: unknown route "${route}"`);
  const tail = segments.filter(s => s != null && s !== "").map(s => encodeURIComponent(String(s)));
  return `${l.prefix}/${seg}${tail.length ? "/" + tail.join("/") : ""}`;
}

export function labelL(loc, s) {
  const l = resolve(loc);
  if (s == null) return "";
  const map = LABELS[l.code] || {};
  return Object.prototype.hasOwnProperty.call(map, s) ? map[s] : String(s);
}

function groupThousands(n, sep) {
  const s = Math.abs(Math.round(n)).toString().replace(/\B(?=(\d{3})+(?!\d))/g, sep);
  return (n < 0 ? "-" : "") + s;
}

export function fmtNumL(loc, n) {
  const l = resolve(loc);
  if (n == null || !isFinite(n)) return "—";
  if (l.code === "pt") return fmtNum(n);
  return groupThousands(n, l.code === "fr" ? NNBSP : ".");
}

export function fmtEurL(loc, n) {
  const l = resolve(loc);
  if (n == null || !isFinite(n)) return "—";
  if (l.code === "pt") return fmtEur(n);
  return `${fmtNumL(l, n)}${NNBSP}€`;
}

export function fmtKmL(loc, n) {
  const l = resolve(loc);
  if (n == null || !isFinite(n)) return "—";
  if (l.code === "pt") return fmtKm(n);
  return `${fmtNumL(l, n)} km`;
}

export function fmtPctL(loc, p, digits = 0) {
  const l = resolve(loc);
  if (p == null || !isFinite(p)) return "—";
  let v = (p * 100).toFixed(digits);
  if (l.code !== "pt" && digits > 0) v = v.replace(".", ",");
  if (l.code === "de" || l.code === "fr") return `${v}${NNBSP}%`;
  return `${v}%`;
}

export function fmtDateL(loc, iso) {
  const l = resolve(loc);
  const m = (typeof iso === "string") ? iso.match(/^(\d{4})-(\d{2})-(\d{2})/) : null;
  if (!m) return "";
  const mon = MONTHS[l.code][+m[2] - 1];
  if (!mon) return "";
  const d = +m[3];
  if (l.code === "de") return `${d}. ${mon} ${m[1]}`;
  return `${d} ${mon} ${m[1]}`;
}

export function monthTagL(loc, iso) {
  const l = resolve(loc);
  const m = /^(\d{4})-(\d{2})/.exec(iso || "");
  if (!m || +m[2] < 1 || +m[2] > 12) return "";
  const mon = MONTHS[l.code][+m[2] - 1];
  return l.code === "pt" ? `${mon}/${m[1]}` : `${mon} ${m[1]}`;
}

export function localeForPath(pathname, enabled) {
  const m = /^\/([a-z]{2})(\/.*)?$/.exec(pathname || "");
  if (!m) return null;
  const code = m[1];
  if (code === "pt" || !LOCALES[code] || !enabled || !enabled.has(code)) return null;
  return { loc: LOCALES[code], rest: m[2] || "" };
}

